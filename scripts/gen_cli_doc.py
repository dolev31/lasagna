"""Write docs/reference/cli.md from the ``lasagna`` command line's own definitions.

    python scripts/gen_cli_doc.py           # rewrite the page
    python scripts/gen_cli_doc.py --check   # exit 1 if the page is out of date

The source is the Typer app in ``src/lasagna/cli.py``, read through the click
command tree Typer builds from it: every command, its description, its
arguments, and each option with its type, default and help text. Hidden
commands are left out, as they are from ``lasagna --help``. Nothing is run and
no model is loaded, so the page is the same on every machine.
``tests/test_cli_doc_current.py`` runs the check, so a flag added without
regenerating the page fails the suite.
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "cli.md"

HEADER = """\
# Command line reference

Generated by `scripts/gen_cli_doc.py` from the Typer app in `src/lasagna/cli.py`.
Do not edit by hand: run the script.

Every command is `lasagna <command> [options]`. `lasagna <command> --help` prints
the same text in your terminal. Commands are grouped by what they work on:

{index}

Options that apply before any command:

{globals}
"""

GROUP_TITLES = {
    "benchmark": "Benchmarks",
    "component": "Components",
    "results": "Results",
    "plugins": "Plugins",
    "pipelines": "Pipelines",
    "skills": "Skills",
}

GROUP_BLURBS = {
    "documents": "Put documents into a session and search them.",
    "benchmark": "Run benchmarks and sweeps, and read what they say about your change.",
    "component": "List the components that fill each stage, and check one of yours.",
    "results": "Read, compare, test and publish what a run wrote.",
    "plugins": "See which installed packages add components or benchmarks.",
    "pipelines": "See the agentic RAG pipelines you can select.",
    "skills": "Install the agent skill that teaches a coding agent to use Lasagna.",
    "setup": "Set up, configure, diagnose and serve.",
}


def _escape(text: str) -> str:
    """Make help text safe in a Markdown table cell, leaving `code spans` alone."""
    parts = re.split(r"(`[^`]*`)", text)
    out = []
    for i, part in enumerate(parts):
        if i % 2:
            out.append(part.replace("|", "\\|"))
        else:
            out.append(part.replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|").replace("*", "\\*"))
    return "".join(out)


def _cell(text: str) -> str:
    return _escape(" ".join((text or "").split()))


def _body(text: str) -> str:
    """A command's description as Markdown paragraphs.

    Lines inside a paragraph are joined, because the source wraps them for a
    terminal. A paragraph whose lines are all indented is kept as a code block.
    """
    text = inspect.cleandoc(text or "")
    blocks: List[str] = []
    for para in re.split(r"\n\s*\n", text):
        lines = para.splitlines()
        if not lines:
            continue
        if all(line.startswith((" ", "\t")) for line in lines):
            blocks.append("```text\n" + "\n".join(inspect.cleandoc(para).splitlines()) + "\n```")
        elif any(line.lstrip().startswith(("- ", "* ", "$ ", "lasagna ")) for line in lines[1:]) or lines[0].startswith(("$ ", "lasagna ")):
            # A list or a shell example: keep the lines as written.
            if lines[0].startswith(("$ ", "lasagna ")) or all(
                line.lstrip().startswith(("$ ", "lasagna ", "#")) or line.startswith(" ") for line in lines
            ):
                blocks.append("```console\n" + "\n".join(lines) + "\n```")
            else:
                blocks.append(_escape_para("\n".join(lines)))
        else:
            blocks.append(_escape_para(" ".join(line.strip() for line in lines)))
    return "\n\n".join(blocks)


def _escape_para(text: str) -> str:
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(
        p if i % 2 else p.replace("<", "&lt;").replace(">", "&gt;").replace("*", "\\*")
        for i, p in enumerate(parts)
    )


def _first_sentence(text: str) -> str:
    first = inspect.cleandoc(text or "").split("\n\n")[0]
    return " ".join(first.split())


def _is_argument(param) -> bool:
    # Typer 0.27 vendors click, so isinstance against the installed click fails.
    return "Argument" in type(param).__name__


def _is_group(cmd) -> bool:
    return hasattr(cmd, "commands")


def _default(param) -> str:
    if _is_argument(param):
        return ""
    if param.is_flag:
        return "off" if not param.default else "on"
    if param.default is None or param.default == "":
        return ""
    return f"`{param.default}`"


def _type(param) -> str:
    if param.is_flag:
        return ""
    name = param.type.name.upper()
    if hasattr(param.type, "choices"):
        return " | ".join(param.type.choices)
    return {"STRING": "text", "INTEGER": "int", "FLOAT": "float", "BOOLEAN": "bool", "PATH": "path"}.get(name, name.lower())


def _options_table(cmd) -> List[str]:
    args = [p for p in cmd.params if _is_argument(p)]
    opts = [p for p in cmd.params if not _is_argument(p) and p.name != "help"]
    lines: List[str] = []
    if args:
        lines += ["**Arguments**", "", "| Argument | Required | Description |", "|---|:--:|---|"]
        for p in args:
            label = p.human_readable_name.upper() + ("..." if p.nargs == -1 else "")
            lines.append(f"| `{label}` | {'yes' if p.required else 'no'} | {_cell(getattr(p, 'help', '') or '')} |")
        lines.append("")
    if opts:
        lines += ["**Options**", "", "| Option | Type | Default | Description |", "|---|---|---|---|"]
        for p in opts:
            names = ", ".join(f"`{n}`" for n in sorted(p.opts, key=lambda n: (not n.startswith("--"), n)))
            if p.secondary_opts:
                names += " / " + ", ".join(f"`{n}`" for n in p.secondary_opts)
            lines.append(f"| {names} | {_type(p)} | {_default(p)} | {_cell(p.help or '')} |")
        lines.append("")
    return lines


def _usage(cmd, path: str) -> str:
    pieces = []
    if any(not _is_argument(p) and p.name != "help" for p in cmd.params):
        pieces.append("[OPTIONS]")
    for p in cmd.params:
        if _is_argument(p):
            name = p.human_readable_name.upper() + ("..." if p.nargs == -1 else "")
            pieces.append(name if p.required else f"[{name}]")
    return " ".join([path, *pieces])


def _visible(group):
    return [(name, cmd) for name, cmd in sorted(group.commands.items()) if not getattr(cmd, "hidden", False)]


def _command_section(cmd, path: str, level: int) -> List[str]:
    h = "#" * level
    lines = [f"{h} `{path}`", "", f"```console\n$ {_usage(cmd, path)}\n```", ""]
    body = _body(cmd.help or "")
    if body:
        lines += [body, ""]
    lines += _options_table(cmd)
    return lines


def render() -> str:
    import typer

    from lasagna import cli

    root = typer.main.get_command(cli.app)

    top_plain = [(n, c) for n, c in _visible(root) if not _is_group(c)]
    groups = [(n, c) for n, c in _visible(root) if _is_group(c)]

    documents = [x for x in top_plain if x[0] in ("init", "upload", "search", "status", "export", "import")]
    setup = [x for x in top_plain if x[0] in ("configure", "doctor", "serve")]
    left = {n for n, _ in top_plain} - {n for n, _ in documents + setup}
    if left:  # a new top-level command must be placed on purpose
        raise SystemExit(f"gen_cli_doc.py: place these commands in a section: {sorted(left)}")

    sections = [("documents", "Documents", documents)]
    for name, grp in groups:
        sections.append((name, GROUP_TITLES.get(name, name.capitalize()), [(f"{name} {n}", c) for n, c in _visible(grp)]))
    sections.append(("setup", "Setup and serving", setup))
    order = ["documents", "benchmark", "results", "component", "plugins", "pipelines", "skills", "setup"]
    sections.sort(key=lambda s: order.index(s[0]) if s[0] in order else len(order))

    index_rows = ["| Group | Commands | What it is for |", "|---|---|---|"]
    for key, title, cmds in sections:
        anchor = _anchor(title)
        names = ", ".join(f"`{n}`" for n, _ in cmds)
        blurb = GROUP_BLURBS.get(key, _first_sentence(dict(groups).get(key).help) if key in dict(groups) else "")
        index_rows.append(f"| [{title}](#{anchor}) | {names} | {blurb} |")

    glob_rows = ["| Option | Description |", "|---|---|"]
    for p in root.params:
        if p.name in ("install_completion", "show_completion"):
            continue
        names = ", ".join(f"`{n}`" for n in sorted(p.opts, key=lambda n: (not n.startswith("--"), n)))
        glob_rows.append(f"| {names} | {_cell(p.help or '')} |")
    glob_rows.append("| `--install-completion`, `--show-completion` | Install shell completion, or print it to copy. |")

    out: List[str] = [HEADER.format(index="\n".join(index_rows), globals="\n".join(glob_rows)).rstrip(), ""]
    for key, title, cmds in sections:
        out += [f"## {title}", ""]
        if key in GROUP_BLURBS:
            out += [GROUP_BLURBS[key], ""]
        for name, cmd in cmds:
            out += _command_section(cmd, f"lasagna {name}", 3)
    text = "\n".join(out).rstrip() + "\n"
    return re.sub(r"\n{3,}", "\n\n", text)


def _anchor(title: str) -> str:
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).strip().replace(" ", "-")


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    args = ap.parse_args(argv)
    sys.path.insert(0, str(ROOT / "src"))
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_cli_doc.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
