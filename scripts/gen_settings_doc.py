"""Write docs/reference/settings.md from the settings' own definitions.

    python scripts/gen_settings_doc.py           # rewrite the page
    python scripts/gen_settings_doc.py --check   # exit 1 if the page is out of date

One row per setting: its type and allowed values, its default, its environment
variable and a one-line description. The source is ``src/lasagna/core/config.py``
(the defaults dict, its comments and the property docstrings) and the
``[rag]`` table of ``src/lasagna/settings.lasagna.toml`` for the settings only
that file defines. A last section lists the variables that are not settings
(server, MCP, vector store connections), from ``SERVER_ENV`` in config.py. Nothing is imported that reads the environment, so the page
is the same on every machine. ``tests/test_settings_doc_current.py`` runs the
check, so a setting added without regenerating the page fails the suite.
"""

from __future__ import annotations

import argparse
import ast
import io
import json
import re
import sys
import tokenize
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "src" / "lasagna" / "core" / "config.py"
TOML = ROOT / "src" / "lasagna" / "settings.lasagna.toml"
SCHEMA = ROOT / "src" / "lasagna" / "configurator" / "schema.py"
OUT = ROOT / "docs" / "reference" / "settings.md"

HEADER = """\
# Settings reference

Generated by `scripts/gen_settings_doc.py` from `src/lasagna/core/config.py` and
`src/lasagna/settings.lasagna.toml`. Do not edit by hand: run the script.

Where a setting comes from, lowest priority first:

1. the default below;
2. `settings.lasagna.toml`, `[rag]` table (`LASAGNA_SETTINGS_FILE` names another file);
3. the environment variable: `LASAGNA_<NAME>`, or `RAG_<NAME>` (the older name, still
   read; `LASAGNA_` wins when both are set). `LASAGNA_LOG_LEVEL` is the exception:
   it sets the CLI's console log level, so `log_level` is `RAG_LOG_LEVEL` only;
4. the session (`lasagna configure --profile <name> -s <session>`, the REST API or MCP).

The settings file and environment variables are the process defaults. A
session's profile and overrides are kept in the session database and win over
both for that session only.

An environment variable that does not parse, or is outside the allowed values,
stops the process with an error naming it. A `RAG_` variable that is not a
setting is ignored with a warning that suggests the closest one. Booleans take
`true`/`false`, `1`/`0`, `yes`/`no` or `on`/`off`; lists and objects take JSON.

Data lives in `~/.lasagna` (`LASAGNA_DATA_DIR`): the databases in `dbs/`
(`LASAGNA_DB_DIR`) and uploads in `uploads/` (`LASAGNA_UPLOAD_DIR`). A
`~/.rag_knowledge` from an earlier version is moved there on first use.
"""


def _comments(source: str) -> Dict[int, str]:
    out: Dict[int, str] = {}
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            out[tok.start[0]] = tok.string.lstrip("#").strip()
    return out


def _module_constant(tree: ast.Module, name: str) -> Any:
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            value = node.value
            if isinstance(value, ast.Call):  # frozenset({...})
                value = value.args[0]
            return ast.literal_eval(value)
    raise KeyError(name)


def _defaults(tree: ast.Module, source: str, comments: Dict[int, str]) -> List[dict]:
    """The defaults dict, in order, with each key's section and comment."""
    sections: List[Tuple[int, str]] = []
    lines = source.splitlines()
    for lineno, text in sorted(comments.items()):
        own_line = lines[lineno - 1].strip().startswith("#")
        prev = lines[lineno - 2].strip() if lineno >= 2 else ""
        after = lines[lineno].strip() if lineno < len(lines) else ""
        if own_line and prev.startswith("# ====") and after.startswith("# ===="):
            sections.append((lineno, text))

    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "default_config" for t in node.targets
        ):
            break
    else:
        raise RuntimeError("default_config not found in config.py")

    rows = []
    for key_node, value_node in zip(node.value.keys, node.value.values):
        key = key_node.value
        section = next((t for ln, t in reversed(sections) if ln < key_node.lineno), "Other")
        # A trailing comment on the value's last line, else the comment block
        # right above the key.
        note = comments.get(value_node.end_lineno, "")
        if not note:
            above, ln = [], key_node.lineno - 1
            while ln in comments and lines[ln - 1].strip().startswith("#"):
                if comments[ln].startswith("===="):
                    break
                above.insert(0, comments[ln])
                ln -= 1
            note = " ".join(above)
        try:
            default = ast.literal_eval(value_node)
            literal = True
        except ValueError:
            default, literal = ast.get_source_segment(source, value_node), False
        rows.append(
            {"key": key, "section": section, "default": default, "literal": literal, "note": note}
        )
    return rows


def _docstrings(tree: ast.Module) -> Dict[str, str]:
    out = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "RAGConfig":
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and any(
                    isinstance(d, ast.Name) and d.id == "property" for d in item.decorator_list
                ):
                    doc = ast.get_docstring(item)
                    if doc:
                        out[item.name] = doc.strip().split("\n\n")[0].replace("\n", " ")
    return out


def _schema_descriptions() -> Dict[str, str]:
    """The configurator's one-line description of each top-level setting.

    Read from the source rather than imported: the module computes one default
    from the environment, and this page must not depend on it.
    """
    out: Dict[str, str] = {}
    for node in ast.walk(ast.parse(SCHEMA.read_text())):
        if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "ParameterDef":
            kw = {k.arg: k.value for k in node.keywords}
            if "parent_key" in kw or "key" not in kw or "description" not in kw:
                continue
            try:
                out[ast.literal_eval(kw["key"])] = ast.literal_eval(kw["description"])
            except ValueError:
                continue
    return out


def _toml_rag() -> Tuple[Dict[str, Any], Dict[str, str]]:
    try:
        import tomllib
    except ImportError:  # Python 3.10
        import tomli as tomllib  # type: ignore[no-redef]

    data = tomllib.loads(TOML.read_text())["rag"]
    notes: Dict[str, str] = {}
    in_rag = False
    for line in TOML.read_text().splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            in_rag = stripped == "[rag]"
            continue
        match = re.match(r"^([a-z_0-9]+)\s*=.*?#\s*(.+)$", stripped)
        if in_rag and match:
            notes[match.group(1)] = match.group(2).strip()
    return data, notes


#: Settings-file tables with no comment of their own to describe them.
_TABLE_NOTES = {
    "document_awareness": "What the agent is told about each document: a preview of its first "
    "tokens, an LLM summary, or both.",
}


def _type(key: str, default: Any, literal: bool, consts: Dict[str, Any]) -> str:
    nullable = consts["nullable"].get(key)
    if nullable:
        kind = nullable
    elif not literal:
        kind = "int"
    elif isinstance(default, bool):
        kind = "bool"
    elif isinstance(default, int):
        kind = "int"
    elif isinstance(default, float):
        kind = "float"
    elif isinstance(default, list):
        kind = "list"
    elif isinstance(default, dict):
        kind = "object"
    else:
        kind = "str"
    if nullable:
        kind += " or none"
    if key in consts["ranges"]:
        lo, hi = consts["ranges"][key]
        kind += f", {lo} to {hi}"
    if key in consts["choices"]:
        kind += ": " + ", ".join(f"`{c}`" for c in consts["choices"][key])
    return kind


def _fmt_default(default: Any, literal: bool) -> str:
    if not literal:
        return f"`{default}`"
    if default is None:
        return "none"
    text = json.dumps(default, ensure_ascii=False)
    if len(text) > 60:
        text = text[:57] + "..."
    return f"`{text}`".replace("|", "\\|")


def _clean(text: str) -> str:
    text = text.replace(" — ", ", ").replace("—", ", ").replace("–", " to ")
    text = re.sub(r"\s+", " ", text).strip()
    if text and not text.endswith((".", "?", "!", ")")):
        text += "."
    return text.replace("|", "\\|")


def render() -> str:
    source = CONFIG.read_text()
    tree = ast.parse(source)
    comments = _comments(source)
    consts = {
        "ranges": _module_constant(tree, "_VALID_RANGES"),
        "choices": _module_constant(tree, "_CHOICES"),
        "nullable": {k: v.id for k, v in _nullable_types(tree).items()},
    }
    docs = _docstrings(tree)
    schema = _schema_descriptions()
    defaults = _defaults(tree, source, comments)
    toml, toml_notes = _toml_rag()
    known = {r["key"] for r in defaults}
    extra = [
        {
            "key": k,
            "section": "Agentic retrieval and document awareness (settings file only)",
            "default": v,
            "literal": True,
            "note": toml_notes.get(k, ""),
        }
        for k, v in toml.items()
        if k not in known and k != "lifecycle"
    ]
    prop_only = _module_constant(tree, "_PROPERTY_ONLY_SETTINGS")
    reserved = _module_constant(tree, "LASAGNA_RESERVED_ENV")
    extra += [
        {
            "key": k,
            "section": "Agentic retrieval and document awareness (settings file only)",
            "default": None,
            "literal": True,
            "note": "",
        }
        for k in prop_only
        if k not in known and k not in toml
    ]

    out = [HEADER]
    current: Optional[str] = None
    for row in defaults + extra:
        if row["section"] != current:
            current = row["section"]
            out.append(f"\n## {current}\n")
            out.append("| Setting | Type | Default | Environment variables | Description |")
            out.append("|---|---|---|---|---|")
        key = row["key"]
        kind = _type(key, row["default"], row["literal"], consts)
        if row["default"] is None and key in prop_only:
            kind = "str"
        description = _clean(
            docs.get(key) or row["note"] or schema.get(key) or _TABLE_NOTES.get(key, "")
        )
        names = f"`RAG_{key.upper()}`"
        if f"LASAGNA_{key.upper()}" not in reserved:
            names = f"`LASAGNA_{key.upper()}`, {names}"
        out.append(
            f"| `{key}` | {kind} | {_fmt_default(row['default'], row['literal'])} "
            f"| {names} | {description} |"
        )
    out += _server_section(tree)
    return "\n".join(out) + "\n"


#: Defaults that are words, not values, so they are not set in code.
_PROSE_DEFAULTS = ("unset", "empty", "a random secret", "the packaged", "<")

SERVER_HEADER = """
## Variables that are not settings

The servers, the MCP server and the vector stores read these from the
environment only: not from the settings file, and not per session.
"""


def _server_section(tree: ast.Module) -> List[str]:
    out = [SERVER_HEADER]
    group: Optional[str] = None
    for name, (section, default, description, older) in _module_constant(
        tree, "SERVER_ENV"
    ).items():
        if section != group:
            group = section
            out.append(f"\n### {group}\n")
            out.append("| Variable | Default | Description |")
            out.append("|---|---|---|")
        names = ", ".join(f"`{n}`" for n in (name, *older))
        shown = default if default.startswith(_PROSE_DEFAULTS) else f"`{default}`"
        out.append(f"| {names} | {shown} | {_clean(description)} |")
    return out


def _nullable_types(tree: ast.Module) -> Dict[str, ast.Name]:
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "_NULLABLE_TYPES":
            return {k.value: v for k, v in zip(node.value.keys, node.value.values)}
    raise KeyError("_NULLABLE_TYPES")


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                f"{OUT.relative_to(ROOT)} is out of date. Run: python scripts/gen_settings_doc.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
