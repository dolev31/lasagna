"""Parallel benchmark execution engine.

Runs benchmark tasks concurrently with session isolation, progress
tracking, and checkpoint-based resumption.
"""

from __future__ import annotations

import asyncio
import hashlib
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Tuple

from loguru import logger

from .benchmarks import BenchmarkSample, benchmark_registry
from .checkpoint import CheckpointManager
from .seeding import seed_everything

#: Override keys that steer the harness, never the system under test.
#:
#: Excluded from ``config_hash``, and therefore from the session id and the
#: checkpoint key, and skipped when overrides are pushed onto the pipeline.
#:
#: ``save_trajectories`` decides how much per-query detail is written to the
#: results file. It was missing from this set, so switching it on produced a
#: different config hash: a new session, a cold corpus cache, a checkpoint that
#: could not resume, and two runs that differed only in how much they *recorded*
#: comparing as different systems.
HARNESS_KEYS = frozenset(
    {
        "allow_inert_overrides",
        "save_trajectories",
        # The IR cutoff and the chunk over-fetch factor. Both steer how the
        # harness *measures*; neither is a pipeline setting, and merging them
        # into `pipeline._config` would set them as retrieval settings on a
        # live run.
        "metric_k",
        "retrieval_chunk_overfetch",
        # An arm that answers with no retrieval at all: the harness skips the
        # pipeline query, so the generator gets no passages. Not a pipeline
        # setting, and it changes every generation number, so it is hashed.
        "no_rag",
    }
)

#: The harness keys that change only what is recorded, not any number. Only
#: these are left out of the task hash: metric_k and the over-fetch change
#: the metrics, and leaving them out let --resume restore a result computed
#: under the old values and label it with the new ones.
RECORDING_ONLY_KEYS = frozenset({"allow_inert_overrides", "save_trajectories"})


def _resolved_revision(adapter: Any, benchmark_name: str) -> str:
    """The upstream revision this benchmark was loaded at, or ``""``.

    The adapter's own declaration wins -- BEIR keeps its own catalogue -- and
    the shared registry is the fallback. Empty means the data came from a
    moving reference, which is a fact about the run and is recorded as one.
    """
    try:
        declared = getattr(adapter, "hf_revision", "") or ""
        if declared:
            return str(declared)

        from .datasets import resolve_dataset_revision

        return resolve_dataset_revision(benchmark_name)
    except Exception as exc:  # noqa: BLE001 - provenance must never fail a run
        logger.debug(f"Could not resolve a dataset revision for {benchmark_name}: {exc}")
        return ""


@dataclass
class BenchmarkTask:
    """A single unit of work: one benchmark x one pipeline config x one run."""

    benchmark_name: str
    config_name: str
    config_overrides: Dict[str, Any]
    run_index: int
    split: str = "test"
    n_samples: Optional[int] = None
    seed: int = 42
    mode: str = "auto"  # "auto" | "live" | "generation_only" ("offline" = alias)
    profile: str = "standard"  # Base pipeline profile name
    filters: Dict[str, Any] = field(default_factory=dict)
    session_id: str = ""  # Generated by runner
    max_corpus_docs: int = 0  # 0 = no limit; >0 = cap corpus size for pilot runs
    # Which evaluation tracks run. None is both; ("retrieval",) skips answer
    # generation, so a component sweep needs neither an LLM nor RAGAS.
    tracks: Optional[Tuple[str, ...]] = None
    corpus_fingerprint: str = ""  # SHA-256 of corpus file; populated at ingestion time
    #: "native" for a corpus the benchmark ships, "pooled_gold" for one
    #: assembled from the samples' own gold context. Populated at ingestion.
    corpus_provenance: str = "native"
    #: Upstream dataset revision. Empty means the corpus was loaded from a
    #: moving reference, so "the same benchmark" is an assumption about
    #: someone else's repository rather than a fact about this run.
    hf_revision: str = ""
    #: True when the corpus was cut to max_docs. A metric computed against
    #: part of a corpus is not that benchmark's metric, and the shortfall
    #: is invisible downstream -- retrieval scores simply come out lower.
    corpus_truncated: bool = False
    #: The share of corpus documents allowed to fail ingestion before a task
    #: on that corpus fails (``ingest_failure_tolerance``, default none).
    ingest_failure_tolerance: float = 0.0
    #: None when every corpus document was ingested; otherwise the counts, a
    #: digest of the ingested ids and the first failures. Populated at ingestion.
    corpus_ingest_gap: Optional[Dict[str, Any]] = None
    #: "run" holds the query subset fixed across runs so the spread is
    #: pipeline nondeterminism; "sample" redraws each run. See ``_execute_task``.
    variance_source: str = "run"
    #: What ``mode`` resolved to, and why. Populated at dispatch. Recorded with
    #: the results because "which mode produced this number" cannot be inferred
    #: from the metrics afterwards, and the two modes measure different things.
    resolved_mode: str = ""
    mode_resolution_reason: str = ""
    #: A hash of what the result depends on beyond the task itself: the metric
    #: definitions, the package version, the judge and the environment's
    #: settings (``run_provenance.resume_fingerprint``). Set by the experiment.
    resume_fingerprint: str = ""

    @property
    def task_key(self) -> str:
        """Identifier for checkpointing.

        Includes config_hash (profile + overrides, 48-bit) and a
        sampling_hash so that tasks with different sampling parameters
        (split, n_samples, seed, filters) get distinct checkpoint keys.
        This prevents ``--resume`` from silently restoring stale results
        when sampling parameters change. The resume fingerprint does the same
        for a new metrics version, package version, judge or environment
        setting: a checkpoint from before such a change is never restored.
        """
        key = (
            f"{self.benchmark_name}|{self.config_name}|{self.config_hash}"
            f"|{self.sampling_hash}|{self.mode}|run_{self.run_index}"
        )
        return f"{key}|env_{self.resume_fingerprint}" if self.resume_fingerprint else key

    @property
    def sampling_hash(self) -> str:
        """Hash of sampling parameters (split, n_samples, seed, filters)."""
        import json

        blob = json.dumps(
            {
                "split": self.split,
                "n_samples": self.n_samples,
                "seed": self.seed,
                "filters": self.filters,
            },
            sort_keys=True,
        )
        return hashlib.sha256(blob.encode()).hexdigest()[:12]

    @property
    def config_hash(self) -> str:
        """Hash of profile + overrides + corpus cap for session-ID generation.

        Profile is included so that tasks with identical overrides but
        different base profiles get distinct session IDs.
        max_corpus_docs is included so that pilot runs (e.g. 500-doc)
        never collide with full-corpus runs in checkpoints.

        ``RECORDING_ONLY_KEYS`` are excluded. They change how the run is
        *recorded*, not what it measures, and hashing them made a run with
        trajectory logging on incomparable to the same run with it off. The
        other harness keys (the IR cutoff, the over-fetch) change the numbers,
        so a checkpoint made under one value never stands in for another.
        """
        import json

        hash_data: Dict[str, Any] = {
            "profile": self.profile,
            "overrides": {
                k: v
                for k, v in (self.config_overrides or {}).items()
                if k not in RECORDING_ONLY_KEYS
            },
        }
        if self.max_corpus_docs > 0:
            hash_data["max_corpus_docs"] = self.max_corpus_docs
        if self.tracks:
            hash_data["tracks"] = sorted(self.tracks)
        blob = json.dumps(hash_data, sort_keys=True)
        return hashlib.sha256(blob.encode()).hexdigest()[:12]


@dataclass
class TaskResult:
    """Result from a single benchmark task execution."""

    task_key: str
    benchmark_name: str
    config_name: str
    run_index: int
    metrics: Dict[str, float] = field(default_factory=dict)
    per_sample_scores: List[Dict[str, float]] = field(default_factory=list)
    duration_seconds: float = 0.0
    n_samples: int = 0
    error: Optional[str] = None

    # Cost / latency aggregate stats (populated from per_sample_scores)
    avg_latency_ms: float = 0.0
    p50_latency_ms: float = 0.0
    p95_latency_ms: float = 0.0
    p99_latency_ms: float = 0.0
    #: Tokens, not dollars.
    #:
    #: There used to be `estimated_cost_usd`, `system_cost_usd` and
    #: `eval_cost_usd` here, all three summed from per-sample keys that nothing
    #: ever wrote -- so every published number was `$0.00000`. They are gone
    #: rather than fixed: a price table baked into a bundle is a fabricated
    #: figure, since rates change and differ by tier, region and commitment, and
    #: a reader a year later cannot tell a stale rate from a measurement.
    #: Tokens are what was observed. Multiply by the rate you actually pay.
    #:
    #: `system` is the pipeline under test; `eval` is the judge and RAGAS. Kept
    #: apart because adding them makes an expensive judge look like an expensive
    #: pipeline, which reverses the conclusion a cost comparison is drawn for.
    system_input_tokens: int = 0
    system_output_tokens: int = 0
    system_llm_calls: int = 0
    eval_input_tokens: int = 0
    eval_output_tokens: int = 0
    eval_llm_calls: int = 0

    # -- provenance: what this number was produced from ---------------------
    #: What this task actually ran with: the loaded embedder, the chunker that
    #: built the corpus, the candidate depth, BM25 stemming. The bundle builds
    #: its held-fixed block from this, not from what the base profile declares,
    #: which is how a run on bge-small was recorded as all-MiniLM-L6-v2.
    system: Dict[str, Any] = field(default_factory=dict)
    #: sha256 over the ingested corpus. Already computed for cache keys; the
    #: only checksum that proves two runs saw the same documents.
    corpus_fingerprint: str = ""
    hf_revision: str = ""
    corpus_truncated: bool = False
    #: Documents of the corpus that could not be ingested: None when there were
    #: none. In the comparability key when set (bundle.HELD_FIXED_FIELDS).
    corpus_ingest_gap: Optional[Dict[str, Any]] = None
    #: Where the searchable corpus came from.
    #:
    #: A pooled-gold corpus is assembled from the samples' own gold context,
    #: which makes retrieval measurable on benchmarks that ship no corpus -- but
    #: it holds no hard negatives, so recall against it reads higher than
    #: against a real corpus. Part of the comparability key for that reason:
    #: the two kinds of number must never be compared.
    corpus_provenance: str = "native"
    #: What `mode` resolved to, and why. Cannot be inferred from the metrics.
    resolved_mode: str = ""
    mode_resolution_reason: str = ""
    #: Whether repeated runs varied the pipeline or the query subset.
    variance_source: str = ""
    #: The split actually used, and the seed the sample was drawn with.
    split: str = ""
    sampling_seed: int = 0
    #: sha256 over the sorted query ids, so two runs can be shown to have
    #: scored the same questions without shipping the questions.
    sample_id_digest: str = ""
    #: The settings that distinguish this arm from the others, copied off the
    #: task. `config_name` alone is a label someone chose; these are what was
    #: actually varied, and every consumer that wanted to know which dimension
    #: moved -- `varied_dimensions`, the leaderboard's config column, the
    #: factorial cell identification -- reads it off the *result*, because a
    #: results file is all they have. Without it `varied_dimensions` returned
    #: `[]` for every run ever produced and the leaderboard labelled every row
    #: `_baseline_`.
    config_overrides: Dict[str, Any] = field(default_factory=dict)
    #: The base profile the overrides were applied to. Two arms with identical
    #: overrides but different profiles are different systems.
    profile: str = ""

    # -- derived totals -----------------------------------------------------
    #
    # Properties rather than fields, so they can never disagree with the parts
    # they are made of. The old `total_*` fields were assigned once and then
    # carried around independently of the numbers they summarised.

    @property
    def total_input_tokens(self) -> int:
        return self.system_input_tokens + self.eval_input_tokens

    @property
    def total_output_tokens(self) -> int:
        return self.system_output_tokens + self.eval_output_tokens

    @property
    def total_llm_calls(self) -> int:
        return self.system_llm_calls + self.eval_llm_calls

    @property
    def tokens_measured(self) -> bool:
        """Whether any LLM call was observed.

        Zero tokens is a legitimate reading for a retrieval-only arm, and also
        what an uninstrumented client produces. Reports must distinguish "spent
        nothing" from "we did not look".
        """
        return self.total_llm_calls > 0

    def compute_latency_stats(self) -> None:
        """Populate aggregate latency and token fields from per_sample_scores.

        Latency is summed per query before it is averaged. An end-to-end sample
        contributes two rows -- a retrieval row and a generation row -- and
        averaging 40ms against 900ms describes a query that took 940ms as
        470ms: neither stage, and not the total. `BenchmarkResults.per_query`
        was fixed to sum them and this was not, so the same run reported 470ms
        in every report and 940ms in `results per-query`.
        """
        if not self.per_sample_scores:
            return

        by_sample: Dict[Any, float] = {}
        for index, sample in enumerate(self.per_sample_scores):
            if "latency_ms" not in sample:
                continue
            sample_id = sample.get("_sample_id", index)
            by_sample[sample_id] = by_sample.get(sample_id, 0.0) + float(sample["latency_ms"])
        latencies = list(by_sample.values())
        if latencies:
            self.avg_latency_ms = sum(latencies) / len(latencies)
            self.p50_latency_ms = _percentile(latencies, 50)
            self.p95_latency_ms = _percentile(latencies, 95)
            self.p99_latency_ms = _percentile(latencies, 99)

        def _sum(key: str) -> int:
            return int(sum(s.get(key, 0) for s in self.per_sample_scores))

        self.system_input_tokens = _sum("input_tokens")
        self.system_output_tokens = _sum("output_tokens")
        self.system_llm_calls = _sum("llm_calls")
        # Eval usage is not per-sample -- the judge runs over the whole batch --
        # so it is set directly by the eval function and only accumulated here
        # if a caller happened to record it per sample.
        self.eval_input_tokens += _sum("eval_input_tokens")
        self.eval_output_tokens += _sum("eval_output_tokens")
        self.eval_llm_calls += _sum("eval_llm_calls")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "task_key": self.task_key,
            "benchmark_name": self.benchmark_name,
            "config_name": self.config_name,
            "run_index": self.run_index,
            "metrics": self.metrics,
            "per_sample_scores": self.per_sample_scores,
            "duration_seconds": self.duration_seconds,
            "n_samples": self.n_samples,
            "error": self.error,
            "avg_latency_ms": self.avg_latency_ms,
            "p50_latency_ms": self.p50_latency_ms,
            "p95_latency_ms": self.p95_latency_ms,
            "p99_latency_ms": self.p99_latency_ms,
            "system_input_tokens": self.system_input_tokens,
            "system_output_tokens": self.system_output_tokens,
            "system_llm_calls": self.system_llm_calls,
            "eval_input_tokens": self.eval_input_tokens,
            "eval_output_tokens": self.eval_output_tokens,
            "eval_llm_calls": self.eval_llm_calls,
            "total_llm_calls": self.total_llm_calls,
            "total_input_tokens": self.total_input_tokens,
            "total_output_tokens": self.total_output_tokens,
            "tokens_measured": self.tokens_measured,
            "corpus_fingerprint": self.corpus_fingerprint,
            "corpus_provenance": self.corpus_provenance,
            "hf_revision": self.hf_revision,
            "corpus_truncated": self.corpus_truncated,
            "corpus_ingest_gap": self.corpus_ingest_gap,
            "resolved_mode": self.resolved_mode,
            "mode_resolution_reason": self.mode_resolution_reason,
            "variance_source": self.variance_source,
            "split": self.split,
            "sampling_seed": self.sampling_seed,
            "sample_id_digest": self.sample_id_digest,
            "config_overrides": self.config_overrides,
            "profile": self.profile,
            "system": self.system,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TaskResult":
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


def _sample_id_digest(samples: List[BenchmarkSample]) -> str:
    """Stable digest of which questions were scored.

    Lets two bundles be shown to cover the same queries without either one
    carrying the queries, which matters for benchmarks whose terms forbid
    redistribution.

    **Hashes the question text, not only the id.** It hashed ids alone, and 14
    of 16 adapters assign ``query_id=str(i)`` — a positional index — so the
    digest was a pure function of ``n_samples``: `beir/nfcorpus` and `squad_v2`
    at n=50 both produced ``770b707572088fe8``. A field in the comparability key,
    documented as proof that two runs scored the same questions, certified
    nothing at all.

    Including the text makes it true for every adapter regardless of whether its
    ids are stable, and it still ships no questions — a sha256 prefix is not a
    corpus. The id stays in the input so that two benchmarks which happen to
    share a question still separate.
    """
    parts = sorted(f"{getattr(s, 'query_id', '')}\x1f{getattr(s, 'question', '')}" for s in samples)
    return hashlib.sha256("|".join(parts).encode()).hexdigest()[:16]


class BenchmarkRunner:
    """Parallel benchmark execution engine with checkpointing.

    Example::

        runner = BenchmarkRunner(max_concurrency=4)
        results = await runner.run_tasks(
            tasks=tasks,
            eval_fn=my_eval_function,
            checkpoint=CheckpointManager("/tmp/experiment"),
        )
    """

    def __init__(self, max_concurrency: int = 4) -> None:
        self._semaphore = asyncio.Semaphore(max_concurrency)
        self._max_concurrency = max_concurrency

    async def run_tasks(
        self,
        tasks: List[BenchmarkTask],
        eval_fn: Callable[[BenchmarkTask, List[BenchmarkSample]], "asyncio.Future[TaskResult]"],
        checkpoint: Optional[CheckpointManager] = None,
        progress_callback: Optional[Callable[[int, int, str], None]] = None,
    ) -> List[TaskResult]:
        """Execute all tasks with bounded concurrency.

        Args:
            tasks: List of benchmark tasks to run.
            eval_fn: Async callable ``(task, samples) -> TaskResult``.
                The runner loads samples and passes them to this function.
            checkpoint: Optional checkpoint manager for resumption.
            progress_callback: Optional ``(completed, total, task_key) -> None``.

        Returns:
            List of :class:`TaskResult` (one per task, including restored
            checkpoints).
        """
        results: List[TaskResult] = []
        pending_tasks: List[BenchmarkTask] = []
        total = len(tasks)

        # Restore checkpointed results
        for task in tasks:
            if checkpoint and checkpoint.is_completed(task.task_key):
                cached = checkpoint.load(task.task_key)
                if cached:
                    restored = TaskResult.from_dict(cached)
                    # Back-fill the arm's identity from the task.
                    #
                    # A checkpoint written before these fields existed carries
                    # neither, and `config_hash` excludes them, so those files
                    # still key-match and restore cleanly -- with
                    # `config_overrides={}`. Every `--resume` run therefore
                    # reproduced the original bug exactly: `varied_dimensions`
                    # empty, every treatment arm rendered `_baseline_`.
                    #
                    # Taken from the task rather than trusted from the file,
                    # because the task is what is being run now; a stale value
                    # in an old checkpoint would describe a different arm.
                    if not restored.config_overrides:
                        restored.config_overrides = dict(task.config_overrides or {})
                    if not restored.profile:
                        restored.profile = task.profile
                    results.append(restored)
                    logger.info(f"Restored checkpoint: {task.task_key}")
                    if progress_callback:
                        progress_callback(len(results), total, task.task_key)
                    continue
            pending_tasks.append(task)

        if not pending_tasks:
            logger.info("All tasks restored from checkpoint")
            return results

        logger.info(
            f"Running {len(pending_tasks)} tasks "
            f"({len(results)} restored from checkpoint, "
            f"concurrency={self._max_concurrency})"
        )

        # Assign unique session IDs.
        # Includes config_name so that tasks with different names but
        # identical profile+overrides (same config_hash) get isolated
        # sessions — prevents cross-task interference in live mode.
        for task in pending_tasks:
            if not task.session_id:
                # Hash config_name rather than sanitizing characters, so
                # names like "A/B" vs "A|B" never collapse to the same slug.
                name_hash = hashlib.sha256(
                    task.config_name.encode(),
                ).hexdigest()[:12]
                task.session_id = (
                    f"bench_{task.config_hash}_{name_hash}"
                    f"_{task.benchmark_name.replace('/', '_')}"
                    f"_run{task.run_index}"
                )

        # Run concurrently with semaphore
        async def _run_one(task: BenchmarkTask) -> TaskResult:
            async with self._semaphore:
                return await self._execute_task(task, eval_fn, checkpoint)

        # Pre-create Tasks in YAML config order before passing to as_completed().
        # asyncio.as_completed() internally calls set(fs) which randomizes coroutine
        # order before creating Tasks. Since asyncio.Semaphore uses a FIFO waiter
        # queue, random Task creation order leads to non-deterministic execution order.
        # Pre-creating Tasks preserves YAML config order in the semaphore queue.
        pending_task_objects = [asyncio.ensure_future(_run_one(t)) for t in pending_tasks]

        for coro in asyncio.as_completed(pending_task_objects):
            result = await coro
            results.append(result)
            if progress_callback:
                progress_callback(len(results), total, result.task_key)

        return results

    async def _execute_task(
        self,
        task: BenchmarkTask,
        eval_fn: Callable,
        checkpoint: Optional[CheckpointManager],
    ) -> TaskResult:
        """Execute a single task with error handling."""
        start = time.monotonic()
        try:
            # What repeated runs are allowed to vary.
            #
            # "run"    — same queries every run, so the spread across runs is
            #            pipeline nondeterminism. This is what "+/- std" is read
            #            as, and what a claim of run-to-run stability needs.
            # "sample" — a different draw each run, so the spread is sampling
            #            variance of the metric over the dataset. Also useful,
            #            but a different quantity, and it was the old behaviour
            #            while the reports described the first one.
            sampling_seed = (
                task.seed if task.variance_source == "run" else task.seed + task.run_index
            )

            # Seed the process itself, not just the sampler: everything from
            # torch to a component's own RNG runs downstream of here.
            seed_everything(task.seed + task.run_index, quiet=True)

            adapter = benchmark_registry.get(task.benchmark_name)
            samples = adapter.load(
                split=task.split,
                n_samples=task.n_samples,
                seed=sampling_seed,
                filters=task.filters if task.filters else None,
            )

            # Which upstream revision this actually loaded. Nothing set it
            # before, so `hf_revision` was empty on every result ever produced
            # and `UNPINNED_DATASET` fired unconditionally -- a warning nobody
            # could act on, which is a warning nobody reads.
            task.hf_revision = task.hf_revision or _resolved_revision(adapter, task.benchmark_name)

            logger.info(f"Running {task.task_key} ({len(samples)} samples, mode={task.mode})")

            # Delegate to eval function
            result = await eval_fn(task, samples)
            result.duration_seconds = time.monotonic() - start

            # Carry the run's identity onto the result.
            #
            # All of this was computed and then thrown away. The corpus
            # fingerprint in particular is a sha256 over the ingested corpus
            # that the harness already calculates for cache keys -- the one
            # checksum proving two runs saw the same documents -- and it never
            # reached the output file. Without these, "which split, which mode,
            # which corpus" cannot be answered from a results file at all.
            result.corpus_fingerprint = task.corpus_fingerprint
            result.corpus_provenance = task.corpus_provenance
            result.hf_revision = task.hf_revision
            result.corpus_truncated = task.corpus_truncated
            result.corpus_ingest_gap = task.corpus_ingest_gap
            result.resolved_mode = task.resolved_mode or task.mode
            result.mode_resolution_reason = task.mode_resolution_reason
            result.variance_source = task.variance_source
            result.split = task.split
            result.sampling_seed = sampling_seed
            result.sample_id_digest = _sample_id_digest(samples)
            result.config_overrides = dict(task.config_overrides or {})
            result.profile = task.profile
            # Only set n_samples if the eval function didn't already set it
            # (e.g. _eval_offline sets it to len(eval_samples) which may be
            # smaller than len(samples) when only a subset has gold context).
            if result.n_samples == 0:
                result.n_samples = len(samples)

            # Checkpoint
            if checkpoint:
                checkpoint.save(task.task_key, result.to_dict())

            return result

        except Exception as exc:
            duration = time.monotonic() - start
            logger.error(f"Task {task.task_key} failed: {exc}")
            return TaskResult(
                task_key=task.task_key,
                benchmark_name=task.benchmark_name,
                config_name=task.config_name,
                run_index=task.run_index,
                duration_seconds=duration,
                error=str(exc),
                # A failed arm still has an identity. "config_3 crashed" is not
                # actionable; "the arm with enable_reranking=True crashed" is.
                config_overrides=dict(task.config_overrides or {}),
                profile=task.profile,
            )


def _percentile(data: List[float], pct: float) -> float:
    """Compute percentile without numpy."""
    if not data:
        return 0.0
    sorted_data = sorted(data)
    k = (len(sorted_data) - 1) * (pct / 100.0)
    f = int(k)
    c = f + 1
    if c >= len(sorted_data):
        return sorted_data[-1]
    d = k - f
    return sorted_data[f] * (1 - d) + sorted_data[c] * d
