"""Contextual Retrieval: Anthropic-style chunk enrichment.

Prepends each chunk with a short context description generated by an LLM,
placing the chunk within the broader document. This dramatically reduces
retrieval failure rates (-67%, Anthropic Sep 2024).

Reference: https://www.anthropic.com/news/contextual-retrieval
"""

import hashlib
import asyncio
from collections import OrderedDict
from typing import Dict, List, Optional
from loguru import logger


class ContextualEnricher:
    """Enriches document chunks with contextual information.

    For each chunk, generates a short context prefix using an LLM that
    explains where the chunk fits within the full document. This context
    is prepended to the chunk before embedding, making retrieval more
    accurate.

    Uses LRU caching to avoid re-computation for identical (document, chunk) pairs.
    """

    CONTEXT_PROMPT = (
        "Here is the full document:\n"
        "<document>\n{document}\n</document>\n\n"
        "Here is the chunk we want to situate within the document:\n"
        "<chunk>\n{chunk}\n</chunk>\n\n"
        "Please give a short succinct context to situate this chunk within "
        "the overall document for the purposes of improving search retrieval "
        "of the chunk. Answer only with the succinct context and nothing else."
    )

    # Default max cache entries to prevent unbounded memory growth
    DEFAULT_MAX_CACHE_SIZE = 10000

    def __init__(
        self,
        llm_provider=None,
        cache: Optional[Dict[str, str]] = None,
        max_cache_size: int = DEFAULT_MAX_CACHE_SIZE,
    ):
        """Initialize the contextual enricher.

        Args:
            llm_provider: LLM provider instance for generating context.
                         Must have a `generate(prompt: str) -> str` method
                         or `agenerate(prompt: str) -> str` async method.
            cache: Optional pre-populated cache mapping (doc_hash, chunk_hash) -> context
            max_cache_size: Maximum cache entries before LRU eviction
        """
        self._llm = llm_provider
        self._cache: OrderedDict[str, str] = OrderedDict(cache or {})
        self._max_cache_size = max_cache_size

    def _cache_put(self, key: str, value: str) -> None:
        """Add to cache with LRU eviction."""
        self._cache[key] = value
        self._cache.move_to_end(key)
        while len(self._cache) > self._max_cache_size:
            self._cache.popitem(last=False)

    @staticmethod
    def _hash_key(document: str, chunk: str) -> str:
        """Create a cache key from document and chunk hashes.

        Uses 24-char hex (96-bit) truncation per component to avoid
        birthday-paradox collisions at scale while keeping keys compact.
        """
        doc_hash = hashlib.sha256(document.encode()).hexdigest()[:24]
        chunk_hash = hashlib.sha256(chunk.encode()).hexdigest()[:24]
        return f"{doc_hash}:{chunk_hash}"

    def enrich(self, full_document: str, chunk: str) -> str:
        """Enrich a single chunk with contextual information.

        Args:
            full_document: The complete document text
            chunk: The chunk to enrich

        Returns:
            Enriched chunk with context prefix prepended
        """
        cache_key = self._hash_key(full_document, chunk)

        # Check cache (move to end to maintain LRU order)
        if cache_key in self._cache:
            context = self._cache[cache_key]
            self._cache.move_to_end(cache_key)
            return f"{context}\n\n{chunk}"

        if self._llm is None:
            logger.warning("No LLM provider configured for contextual retrieval")
            return chunk

        prompt = self.CONTEXT_PROMPT.format(
            document=full_document[:50000],  # Truncate very large docs
            chunk=chunk,
        )

        try:
            if hasattr(self._llm, "generate"):
                context = self._llm.generate(prompt)
            elif hasattr(self._llm, "invoke"):
                context = self._llm.invoke(prompt)
            else:
                logger.warning("LLM provider has no generate/invoke method")
                return chunk

            # Handle LangChain-style response objects
            if hasattr(context, "content"):
                context = context.content
            context = str(context).strip()

            # Cache the result (with LRU eviction)
            self._cache_put(cache_key, context)

            logger.debug(f"Generated context ({len(context)} chars) for chunk ({len(chunk)} chars)")
            return f"{context}\n\n{chunk}"

        except Exception as e:
            logger.warning(f"Contextual enrichment failed: {e}")
            return chunk

    async def aenrich(self, full_document: str, chunk: str) -> str:
        """Async version of enrich()."""
        cache_key = self._hash_key(full_document, chunk)

        if cache_key in self._cache:
            context = self._cache[cache_key]
            self._cache.move_to_end(cache_key)
            return f"{context}\n\n{chunk}"

        if self._llm is None:
            return chunk

        prompt = self.CONTEXT_PROMPT.format(
            document=full_document[:50000],
            chunk=chunk,
        )

        try:
            if hasattr(self._llm, "agenerate"):
                context = await self._llm.agenerate(prompt)
            elif hasattr(self._llm, "ainvoke"):
                context = await self._llm.ainvoke(prompt)
            elif hasattr(self._llm, "generate"):
                loop = asyncio.get_running_loop()
                context = await loop.run_in_executor(None, self._llm.generate, prompt)
            else:
                return chunk

            if hasattr(context, "content"):
                context = context.content
            context = str(context).strip()
            self._cache_put(cache_key, context)
            return f"{context}\n\n{chunk}"

        except Exception as e:
            logger.warning(f"Async contextual enrichment failed: {e}")
            return chunk

    def enrich_batch(
        self,
        full_document: str,
        chunks: List[str],
    ) -> List[str]:
        """Enrich a batch of chunks from the same document.

        Args:
            full_document: The complete document text
            chunks: List of chunks to enrich

        Returns:
            List of enriched chunks
        """
        return [self.enrich(full_document, chunk) for chunk in chunks]

    async def aenrich_batch(
        self,
        full_document: str,
        chunks: List[str],
        max_concurrency: int = 5,
    ) -> List[str]:
        """Async batch enrichment with concurrency control.

        Args:
            full_document: The complete document text
            chunks: List of chunks to enrich
            max_concurrency: Maximum concurrent LLM calls

        Returns:
            List of enriched chunks
        """
        semaphore = asyncio.Semaphore(max_concurrency)

        async def _enrich_with_limit(chunk: str) -> str:
            async with semaphore:
                return await self.aenrich(full_document, chunk)

        tasks = [_enrich_with_limit(chunk) for chunk in chunks]
        return await asyncio.gather(*tasks)

    @property
    def cache_size(self) -> int:
        """Number of cached context entries."""
        return len(self._cache)

    def clear_cache(self):
        """Clear the context cache."""
        self._cache.clear()
